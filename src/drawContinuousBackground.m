function drawContinuousBackground(ax, cfg)
%DRAWCONTINUOUSBACKGROUND Draw one uninterrupted, readable campus strip.

ink = cfg.presentation.colors.ink;
blue = cfg.presentation.colors.uiBlue;

% MATLAB origin: the graph remains part of the world rather than a title card.
patch(ax, [0, 12, 12, 0], [0, 0, 11.2, 11.2], ...
    [0.94, 0.97, 0.96], 'EdgeColor', 'none');
plot(ax, [1.0, 1.0], [1.0, 9.4], '-', 'Color', [0.24, 0.34, 0.38], ...
    'LineWidth', 1.8);
plot(ax, [0.8, 11.2], [1.0, 1.0], '-', 'Color', [0.24, 0.34, 0.38], ...
    'LineWidth', 1.8);
x = linspace(1.1, 11.0, 70);
y = 5.0 + 1.1 * sin(0.9 * x) + 0.035 * (x - 6) .^ 2;
plot(ax, x, y, '-', 'Color', [0.76, 0.22, 0.20], 'LineWidth', 2.2);
text(ax, 1.5, 10.2, 'MATLAB 坐标轴入口', ...
    'FontName', cfg.render.fontName, 'FontWeight', 'bold', ...
    'Color', ink, 'FontSize', 14);

% North Lake: water, one supported red-bridge silhouette, and tree scale.
patch(ax, [12, 48, 48, 12], [0.2, 0.2, 6.0, 6.0], ...
    cfg.presentation.colors.water, 'EdgeColor', 'none', 'FaceAlpha', 0.46);
for treeX = 14.5:4.2:46
    plot(ax, treeX, 7.0 + 0.2 * mod(round(treeX), 3), 'o', ...
        'MarkerSize', 23, 'MarkerFaceColor', [0.25, 0.54, 0.31], ...
        'MarkerEdgeColor', [0.14, 0.34, 0.20]);
end
plot(ax, [14.0, 20.5, 27.0], [5.0, 5.7, 5.7], '-', ...
    'Color', [0.65, 0.15, 0.11], 'LineWidth', 5.0);
for supportX = [14.6, 20.5, 26.4]
    plot(ax, [supportX, supportX], [3.5, 5.4], '-', ...
        'Color', [0.35, 0.20, 0.15], 'LineWidth', 2.3);
end
text(ax, 15, 9.2, '北湖 · 动物借道', ...
    'FontName', cfg.render.fontName, 'FontWeight', 'bold', ...
    'Color', [0.12, 0.36, 0.42], 'FontSize', 15);

% The campus-network interface is rebuilt as geometry around its controls.
rectangle(ax, 'Position', [48.4, 0.55, 31.1, 10.6], ...
    'FaceColor', [0.96, 0.98, 1.0], 'EdgeColor', [0.62, 0.72, 0.84], ...
    'LineWidth', 1.4, 'Curvature', 0.02);
rectangle(ax, 'Position', [48.4, 9.55, 31.1, 1.6], ...
    'FaceColor', [0.25, 0.57, 0.84], 'EdgeColor', 'none');
text(ax, 49.4, 10.35, '北京理工大学 · 校园网用户认证', ...
    'FontName', cfg.render.fontName, 'FontWeight', 'bold', ...
    'Color', 'white', 'FontSize', 14);
text(ax, 49.5, 8.75, '通知公告', 'FontName', cfg.render.fontName, ...
    'FontWeight', 'bold', 'Color', ink);
for rowY = [7.9, 7.25, 6.6]
    plot(ax, [49.5, 54.0], [rowY, rowY], '-', ...
        'Color', [0.66, 0.72, 0.78], 'LineWidth', 1.2);
end

% North-to-south transition: road below and supported bridge above.
patch(ax, [80, 132, 132, 80], [0.65, 0.65, 4.1, 4.1], ...
    [0.40, 0.44, 0.47], 'EdgeColor', 'none', 'FaceAlpha', 0.84);
for stripeX = 81:4.5:130
    plot(ax, [stripeX, min(stripeX + 2.2, 132)], [2.5, 2.5], '-', ...
        'Color', [0.95, 0.92, 0.65], 'LineWidth', 1.4);
end
for supportX = [92, 104, 113, 124]
    plot(ax, [supportX, supportX], [4.1, 6.0], '-', ...
        'Color', [0.31, 0.35, 0.38], 'LineWidth', 3.0);
end
text(ax, 84.2, 10.2, '南北交通：喷泉上桥 / 红绿灯过街', ...
    'FontName', cfg.render.fontName, 'FontWeight', 'bold', ...
    'Color', ink, 'FontSize', 14);

% Sanitized Lexue page: no personal profile, dates, course history, or links.
rectangle(ax, 'Position', [132.2, 0.55, 45.6, 10.6], ...
    'FaceColor', [0.94, 0.97, 1.0], 'EdgeColor', [0.48, 0.64, 0.84], ...
    'LineWidth', 1.4);
rectangle(ax, 'Position', [132.2, 9.45, 45.6, 1.7], ...
    'FaceColor', [0.18, 0.37, 0.66], 'EdgeColor', 'none');
text(ax, 133.3, 10.3, '乐 学', 'FontName', cfg.render.fontName, ...
    'FontWeight', 'bold', 'Color', 'white', 'FontSize', 17);
text(ax, 160.6, 10.3, '通知  50', 'FontName', cfg.render.fontName, ...
    'FontWeight', 'bold', 'Color', [1.0, 0.82, 0.25], 'FontSize', 13);
text(ax, 133.4, 8.65, '选课倒计时  →  开始选课  →  我的课程', ...
    'FontName', cfg.render.fontName, 'Color', blue, ...
    'FontWeight', 'bold', 'FontSize', 12);

% Lucy River is the only end-of-journey water zone.
patch(ax, [178, 184, 184, 178], [0.2, 0.2, 6.4, 6.4], ...
    [0.34, 0.76, 0.90], 'EdgeColor', [0.10, 0.47, 0.67], ...
    'LineWidth', 1.5, 'FaceAlpha', 0.72);
text(ax, 181, 7.1, 'Lucy 河', 'HorizontalAlignment', 'center', ...
    'FontName', cfg.render.fontName, 'FontWeight', 'bold', ...
    'Color', [0.06, 0.35, 0.55], 'FontSize', 15);
end
