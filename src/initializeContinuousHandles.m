function [vertices, faces, colours] = busPatchGeometry()
% One patch with multiple coloured faces is much cheaper than seven HG
% objects per vehicle while retaining windows, stripe, wheels and hubs.
polygons = { ...
    [0.02 .12; .98 .12; .98 .84; .91 .95; .09 .95; .02 .84], ...
    [.02 .12; .98 .12; .98 .38; .02 .38], ...
    [.07 .56; .18 .56; .18 .86; .07 .86], ...
    [.22 .56; .34 .56; .34 .86; .22 .86], ...
    [.38 .56; .50 .56; .50 .86; .38 .86], ...
    [.54 .56; .66 .56; .66 .86; .54 .86], ...
    [.70 .56; .82 .56; .82 .86; .70 .86], ...
    [.86 .56; .93 .56; .93 .86; .86 .86]};
theta = linspace(0, 2 * pi, 14)';
for centre = [0.20, 0.80]
    polygons{end + 1} = [centre + .075 * cos(theta), ...
        .13 + .13 * sin(theta)]; %#ok<AGROW>
    polygons{end + 1} = [centre + .032 * cos(theta), ...
        .13 + .055 * sin(theta)]; %#ok<AGROW>
end
faceColours = [235 240 226; 33 122 74; repmat([28 58 72], 6, 1); ...
    20 23 23; 168 181 179; 20 23 23; 168 181 179] / 255;
maxCorners = max(cellfun(@(p) size(p, 1), polygons));
faces = nan(numel(polygons), maxCorners);
vertices = zeros(0, 2);
for index = 1:numel(polygons)
    first = size(vertices, 1) + 1;
    vertices = [vertices; polygons{index}]; %#ok<AGROW>
    faces(index, 1:size(polygons{index}, 1)) = ...
        first:(first + size(polygons{index}, 1) - 1);
end
colours = faceColours;
end

function page = createNetworkPageSurface(ax, rect, imagePath, stride)
stride = max(1, round(stride));
rgb = readGameImage(imagePath, stride);
x = rect(1) + [0, rect(3); 0, rect(3)];
y = rect(2) + [0, 0; rect(4), rect(4)];
page = surface(ax, x, y, 0.02 * ones(2), ...
    'CData', flipud(rgb), 'FaceColor', 'texturemap', ...
    'EdgeColor', 'none', 'Visible', 'off');
end
