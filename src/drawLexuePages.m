    'EdgeColor', edgeColor, 'LineWidth', 0.6, 'FaceAlpha', alpha);
end

function drawPixelText(ax, page, pixelXY, pixels, label, cfg, ...
        fontSize, color, weight, alignment)
point = pixelPoint(page, pixelXY, pixels);
text(ax, point(1), point(2), label, ...
    'HorizontalAlignment', alignment, 'VerticalAlignment', 'middle', ...
    'FontName', cfg.render.fontName, 'FontSize', fontSize, ...
    'FontWeight', weight, 'Color', color, 'Interpreter', 'none');
end

function point = pixelPoint(page, pixelXY, pixels)
scale = page(3) / pixels(1);
point = [page(1) + pixelXY(1) * scale, ...
    page(2) + (pixels(2) - pixelXY(2)) * scale];
end
