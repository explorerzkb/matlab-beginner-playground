function drawSelectionTimeline(ax, page, pixelRect, pixels, cfg)
timeline = pixelRectToWorld(page, pixelRect, pixels);
lineX = timeline(1) + 0.35 * timeline(3);
plot(ax, [lineX, lineX], ...
    [timeline(2) + 0.15 * timeline(4), ...
     timeline(2) + 0.85 * timeline(4)], '-', ...
    'Color', [0.87, 0.92, 1.0], 'LineWidth', 1.0);
for fraction = [0.15, 0.85]
    y = timeline(2) + fraction * timeline(4);
    plot(ax, lineX, y, 'o', 'MarkerSize', 6, ...
        'MarkerFaceColor', [0.33, 0.55, 0.88], ...
        'MarkerEdgeColor', 'white', 'LineWidth', 0.9);
end
text(ax, timeline(1) - 0.08, timeline(2) + 0.50 * timeline(4), ...
    sprintf('第二轮预选\n抽签'), 'HorizontalAlignment', 'right', ...
    'VerticalAlignment', 'middle', 'FontName', cfg.render.fontName, ...
    'FontSize', 6.0, 'FontWeight', 'bold', 'Color', 'white');
text(ax, timeline(1) + 0.55 * timeline(3), ...
    timeline(2) + 0.79 * timeline(4), '匿名开始', ...
    'FontName', cfg.render.fontName, 'FontSize', 5.2, 'Color', 'white');
text(ax, timeline(1) + 0.55 * timeline(3), ...
    timeline(2) + 0.09 * timeline(4), '匿名结束', ...
    'FontName', cfg.render.fontName, 'FontSize', 5.2, 'Color', 'white');
end

