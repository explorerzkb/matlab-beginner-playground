function drawDetailedCampusLayer(ax, scene, cfg)
%DRAWDETAILEDCAMPUSLAYER Add school-specific structure without collision.
% These objects live in the non-playable middle/far layers.

switch scene
    case 'northLake'
        drawNorthLakeCampus(ax, cfg);
    case 'networkBridge'
        drawNetworkCampus(ax, cfg);
    case 'navigation'
        drawNavigationCampus(ax, cfg);
    case 'deadlineStorm'
        drawDeadlineCampus(ax, cfg);
end
end

