function drawBuilding(ax, x, y, width, height, bodyColor, accentColor, ...
        columns, rows, label, cfg)
rectangle(ax, 'Position', [x, y, width, height], ...
    'FaceColor', bodyColor, 'EdgeColor', accentColor, 'LineWidth', 1.3);
rectangle(ax, 'Position', [x, y + height - 0.28, width, 0.28], ...
    'FaceColor', accentColor, 'EdgeColor', accentColor);

marginX = 0.45;
marginTop = 0.48;
doorWidth = min(0.75, width / 5);
windowWidth = max(0.20, (width - 2 * marginX) / columns * 0.55);
windowHeight = max(0.16, (height - 0.95) / rows * 0.42);
for row = 1:rows
    windowY = y + height - marginTop - row * ((height - 0.85) / rows);
    for column = 1:columns
        centreX = x + marginX + (column - 0.5) * ...
            ((width - 2 * marginX) / columns);
        rectangle(ax, 'Position', [centreX - windowWidth / 2, windowY, ...
            windowWidth, windowHeight], 'FaceColor', [0.70, 0.88, 0.94], ...
            'EdgeColor', [0.36, 0.53, 0.61], 'LineWidth', 0.6);
    end
end
rectangle(ax, 'Position', [x + width / 2 - doorWidth / 2, y, ...
    doorWidth, min(0.65, height * 0.28)], 'FaceColor', accentColor, ...
    'EdgeColor', accentColor);
text(ax, x + 0.22, y + height - 0.12, label, ...
    'FontName', cfg.render.fontName, 'FontSize', 7.5, ...
    'Color', [1, 1, 1], 'VerticalAlignment', 'middle');
end

function drawTree(ax, x, y, scale)
rectangle(ax, 'Position', [x - 0.08 * scale, y, 0.16 * scale, 0.70 * scale], ...
    'FaceColor', [0.39, 0.25, 0.14], 'EdgeColor', 'none');
t = linspace(0, 2 * pi, 22);
centres = [x - 0.24 * scale, y + 0.70 * scale; ...
           x + 0.20 * scale, y + 0.76 * scale; ...
           x, y + 1.00 * scale];
colors = [0.25, 0.53, 0.30; 0.34, 0.63, 0.34; 0.20, 0.46, 0.27];
for index = 1:3
    patch(ax, centres(index, 1) + 0.38 * scale * cos(t), ...
        centres(index, 2) + 0.34 * scale * sin(t), colors(index, :), ...
        'EdgeColor', [0.17, 0.38, 0.22], 'LineWidth', 0.7);
end
end

function drawLamp(ax, x, y, height)
plot(ax, [x, x], [y, y + height], '-', 'Color', [0.23, 0.30, 0.32], ...
    'LineWidth', 1.4);
plot(ax, [x, x + 0.28], [y + height, y + height], '-', ...
    'Color', [0.23, 0.30, 0.32], 'LineWidth', 1.4);
plot(ax, x + 0.30, y + height - 0.04, 'o', 'MarkerSize', 5, ...
    'MarkerFaceColor', [1.00, 0.92, 0.60], ...
    'MarkerEdgeColor', [0.30, 0.34, 0.32]);
end

function drawCampusSign(ax, x, y, labels, color, cfg)
width = 3.7;
height = 1.05;
rectangle(ax, 'Position', [x, y, width, height], ...
    'FaceColor', color, 'EdgeColor', [0.95, 0.96, 0.91], ...
    'LineWidth', 1.1, 'Curvature', 0.05);
plot(ax, [x + 0.35, x + 0.35], [y - 0.55, y], '-', ...
    'Color', [0.26, 0.31, 0.29], 'LineWidth', 2.0);
plot(ax, [x + width - 0.35, x + width - 0.35], [y - 0.55, y], '-', ...
    'Color', [0.26, 0.31, 0.29], 'LineWidth', 2.0);
text(ax, x + width / 2, y + 0.70, labels{1}, ...
    'HorizontalAlignment', 'center', 'FontName', cfg.render.fontName, ...
    'FontWeight', 'bold', 'FontSize', 8.5, 'Color', [1, 1, 1]);
text(ax, x + width / 2, y + 0.29, labels{2}, ...
    'HorizontalAlignment', 'center', 'FontName', cfg.render.fontName, ...
    'FontSize', 7.5, 'Color', [0.90, 0.96, 0.94]);
end

function drawClock(ax, x, y, radius)
t = linspace(0, 2 * pi, 32);
patch(ax, x + radius * cos(t), y + radius * sin(t), [0.96, 0.96, 0.91], ...
    'EdgeColor', [0.25, 0.28, 0.29], 'LineWidth', 1.4);
plot(ax, [x, x], [y, y + 0.35 * radius], '-', ...
    'Color', [0.25, 0.28, 0.29], 'LineWidth', 1.2);
plot(ax, [x, x + 0.42 * radius], [y, y - 0.15 * radius], '-', ...
    'Color', [0.25, 0.28, 0.29], 'LineWidth', 1.2);
end
